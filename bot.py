def load_stats():
    if not os.path.exists(STATS_FILE):
        return {
            "total": 0,
            "triggers": {}
        }

    try:
        with open(STATS_FILE, "r", encoding="utf-8") as file:
            return json.load(file)

    except Exception:
        return {
            "total": 0,
            "triggers": {}
        }


def save_stats(data):
    with open(STATS_FILE, "w", encoding="utf-8") as file:
        json.dump(
            data,
            file,
            ensure_ascii=False,
            indent=4
        )


stats = load_stats()


def increase_stat(trigger):
    stats["total"] += 1

    if trigger not in stats["triggers"]:
        stats["triggers"][trigger] = 0

    stats["triggers"][trigger] += 1

    save_stats(stats)


