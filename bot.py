# سیستم تشخیص سکوت گروه
# =========================================================

async def inactivity_checker(
    context: ContextTypes.DEFAULT_TYPE
):

    if not BOT_ENABLED:
        return

    now = datetime.now(
        timezone.utc
    )

    for chat_id, data in list(
        last_activity.items()
    ):

        try:

            last_message = datetime.fromisoformat(
                data["last_message"]
            )

        except (
            KeyError,
            ValueError
        ):

            continue

        elapsed_hours = (
            now - last_message
        ).total_seconds() / 3600

        # -------------------------------------------------
        # اگر بیشتر از 15 ساعت گذشته باشد
        # -------------------------------------------------

        if (
            elapsed_hours >= INACTIVITY_HOURS
            and not data.get("warned", False)
        ):

            await context.bot.send_message(
                chat_id=int(chat_id),
                text=random.choice(
                    INACTIVITY_MESSAGES
                )
            )

            # جلوگیری از ارسال چند پیام پشت سر هم
            last_activity[chat_id]["warned"] = True

    save_last_activity(
        last_activity
    )


